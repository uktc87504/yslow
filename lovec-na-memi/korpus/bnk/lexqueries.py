PERSONS = {'Acc': ['ме', 'го'], 'Dat': ['ми', 'му']}


def count(q, tries=4):
    for k in range(tries):
        r = subprocess.run([S + '/scripts/bnk.sh', q], capture_output=True, text=True)
        try:
            d = json.loads(r.stdout)
            if d.get('error'):
                return None
            return d['count']
        except Exception:
            time.sleep(2 ** (k + 1))
    return None


done = {}
if os.path.exists(OUT):
    done = {(x['label'], x['clitic']): x for x in json.load(open(OUT, encoding='utf-8'))}


def save():
    json.dump(list(done.values()), open(OUT, 'w', encoding='utf-8'), ensure_ascii=False, indent=0)


def run(label, pol, case, patterns):
    for cl in PERSONS[case]:
        lab = label if cl in ('ме', 'ми') else label + ' [' + cl + ']'
        if (label, cl) in done:
            continue
        tot = neg = 0
        qs = []
        for pat in patterns:
            for base in pat['base']:
                q = base.replace('CL', cl)
                n = count(q); qs.append((q, n)); tot += n or 0
                time.sleep(0.4)
            for nq in pat['neg']:
                q = nq.replace('CL', cl)
                n = count(q); qs.append((q, n)); neg += n or 0
                time.sleep(0.4)
        done[(label, cl)] = dict(label=label, clitic=cl, case=case, pol=pol, total=tot, negated=neg, queries=qs)
        save()
        print(lab, tot, neg, flush=True)


