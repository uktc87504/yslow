LEX = [(a, b, re.compile('^(' + c + ')$')) for a, b, c in LEX]


def lookup(w):
    for i, (lab, pol, rx) in enumerate(LEX):
        if rx.match(w):
            return i
    return -1


def analyze(path, target):
    data = json.load(open(path, encoding='utf-8'))
    out = []
    for s in data['sents']:
        toks = s['toks']
        words = [PUNCT.sub('', t['w']).lower() for t in toks]
        # клауза: граница при пунктуация в края на токена или при съюз
        clause, c = [], 0
        for k, t in enumerate(toks):
            if words[k] in CONJ:
                c += 1
            clause.append(c)
            if PUNCT.search(t['w'][-1:] or ''):
                c += 1
        for i, t in enumerate(toks):
            if not t['m'] or words[i] != target or 'POSS' in t['tag'] or not t['tag'].startswith('P'):
                continue
            hit, j0 = -1, -1
            for d in (1, -1, 2, -2, 3, -3):
                j = i + d
                if 0 <= j < len(toks) and clause[j] == clause[i] and words[j] not in ('ме', 'ми'):
                    k = lookup(words[j])
                    if k >= 0:
                        hit, j0 = k, j
                        break
            neg = any(0 <= j < len(toks) and clause[j] == clause[i] and words[j] == 'не' for j in (i - 1, j0 - 1) if j >= 0)
            rec = dict(file=s['file'], text=' '.join(t['w'] for t in toks), clitic=target)
            if hit < 0:
                rec.update(pol=None)
            else:
                lab, pol, _ = LEX[hit]
                final = pol if not neg else ('neg' if pol == 'pos' else 'neu')
                rec.update(label=lab, base=pol, neg=neg, pol=final, pred=toks[j0]['w'])
            out.append(rec)
    return out


def wilson(k, n, z=1.96):
    if not n:
        return (0, 0)
    p = k / n; d = 1 + z * z / n; c = p + z * z / (2 * n); m = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return ((c - m) / d, (c + m) / d)


if __name__ == '__main__':
    allrecs = []
    for path, tgt in (sys.argv[1], 'ме'), (sys.argv[2], 'ми'):
        recs = analyze(path, tgt)
        allrecs += recs
        c = collections.Counter(r['pol'] for r in recs)
        v = c['neg'] + c['pos']
        lo, hi = wilson(c['neg'], v)
        print(f"{tgt}: лични={len(recs)} експериенцер={len(recs) - c[None]} neg={c['neg']} pos={c['pos']} neu={c['neu']} "
              f"дял neg={c['neg'] / v:.3f} [{lo:.3f}-{hi:.3f}]")
        print('   ', collections.Counter((r['label'], r['pol']) for r in recs if r['pol']).most_common(40))
    json.dump(allrecs, open(sys.argv[3], 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
